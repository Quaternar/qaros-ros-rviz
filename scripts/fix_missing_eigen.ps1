<#
.SYNOPSIS
    Provide Eigen3 (headers + CMake config) in the ROS 2 Humble Windows binary
    distro so downstream ament plugins that find_package(rviz_common) can configure.

.DESCRIPTION
    PACKAGING GAP (discovered in M3):
    find_package(rviz_common) transitively runs
        rviz_common -> rviz_rendering -> find_package(Eigen3 REQUIRED)
    via eigen3_cmake_module's FindEigen3.cmake, which does
    find_package(Eigen3 CONFIG) and requires EIGEN3_FOUND. The official
    release-humble-20260220 Windows archive ships NO Eigen headers and NO
    Eigen3Config.cmake, so every ament plugin build fails with
        "Could NOT find Eigen3 (missing: EIGEN3_FOUND)".

    Eigen is header-only. This script vendors an existing Eigen 3.4.0 (preferring
    the one that ships with the machine's Anaconda, mirroring how M0 sourced the
    OpenSSL 1.1.1 pair from conda) into the distro and writes a self-contained
    Eigen3Config.cmake. Idempotent.

.PARAMETER Ros2DistroRoot
    Default: D:\development\ros2_humble\ros2-windows
.PARAMETER EigenSourceInclude
    Path to a source '.../include/eigen3' directory (contains 'Eigen' + 'signature_of_eigen3_matrix_library').
    If omitted, the script searches the machine's Anaconda for Eigen 3.4.0.
#>
param(
    [string]$Ros2DistroRoot = "D:\development\ros2_humble\ros2-windows",
    [string]$EigenSourceInclude = ""
)

$ErrorActionPreference = "Stop"

if (-not (Test-Path $Ros2DistroRoot)) { throw "ROS 2 distro not found at $Ros2DistroRoot" }

# --- Locate a source Eigen 3.x (include/eigen3) ----------------------------
if (-not $EigenSourceInclude) {
    # Search common per-user Anaconda/Miniconda install roots (not hard-coded to
    # any one account: derived from $env:USERPROFILE / well-known machine-wide
    # locations, so this works unmodified on any machine with a conda Eigen).
    $condaRoots = @(
        "$env:USERPROFILE\anaconda3", "$env:USERPROFILE\miniconda3",
        "C:\ProgramData\anaconda3", "C:\ProgramData\miniconda3"
    ) | Where-Object { Test-Path $_ }
    $candidates = @()
    foreach ($r in $condaRoots) {
        $candidates += (Join-Path $r "Library\include\eigen3")
        Get-ChildItem -Path (Join-Path $r "pkgs") -Directory -Filter "eigen-*" -ErrorAction SilentlyContinue | ForEach-Object {
            $candidates += (Join-Path $_.FullName "Library\include\eigen3")
        }
    }
    foreach ($c in $candidates) {
        if (Test-Path (Join-Path $c "signature_of_eigen3_matrix_library")) { $EigenSourceInclude = $c; break }
    }
    if (-not $EigenSourceInclude) {
        foreach ($r in $condaRoots) {
            $sig = Get-ChildItem -Path $r -Recurse -Filter "signature_of_eigen3_matrix_library" -ErrorAction SilentlyContinue | Select-Object -First 1
            if ($sig) { $EigenSourceInclude = $sig.Directory.FullName; break }
        }
    }
}
if (-not $EigenSourceInclude -or -not (Test-Path (Join-Path $EigenSourceInclude "Eigen"))) {
    throw "Could not locate a source Eigen include dir. Pass -EigenSourceInclude '<...>/include/eigen3'."
}
Write-Host "Eigen source: $EigenSourceInclude" -ForegroundColor Cyan

# --- Copy headers into the distro ------------------------------------------
$destInclude = Join-Path $Ros2DistroRoot "opt\eigen3_vendor\include\eigen3"
if (-not (Test-Path (Join-Path $destInclude "signature_of_eigen3_matrix_library"))) {
    New-Item -ItemType Directory -Force -Path $destInclude | Out-Null
    Copy-Item -Path (Join-Path $EigenSourceInclude "*") -Destination $destInclude -Recurse -Force
    Write-Host "Copied Eigen headers -> $destInclude" -ForegroundColor Green
} else {
    Write-Host "Eigen headers already present -> $destInclude" -ForegroundColor Green
}

# --- Write a self-contained Eigen3Config.cmake -----------------------------
$cmakeDir = Join-Path $Ros2DistroRoot "share\eigen3\cmake"
New-Item -ItemType Directory -Force -Path $cmakeDir | Out-Null

# Forward slashes for CMake.
$incForCMake = ($destInclude -replace '\\', '/')

$config = @"
# Self-contained Eigen3 config generated by scripts/fix_missing_eigen.ps1 to fill
# a packaging gap in the ROS 2 Humble Windows binary distro (no Eigen shipped).
set(EIGEN3_VERSION_STRING "3.4.0")
set(Eigen3_VERSION "3.4.0")
set(EIGEN3_FOUND TRUE)
set(Eigen3_FOUND TRUE)
set(EIGEN3_INCLUDE_DIR "$incForCMake")
set(EIGEN3_INCLUDE_DIRS "$incForCMake")
set(EIGEN3_ROOT_DIR "$incForCMake")

if(NOT TARGET Eigen3::Eigen)
  add_library(Eigen3::Eigen INTERFACE IMPORTED)
  set_target_properties(Eigen3::Eigen PROPERTIES
    INTERFACE_INCLUDE_DIRECTORIES "$incForCMake")
endif()
"@
Set-Content -Path (Join-Path $cmakeDir "Eigen3Config.cmake") -Value $config -Encoding UTF8

$version = @"
set(PACKAGE_VERSION "3.4.0")
if(PACKAGE_VERSION VERSION_LESS PACKAGE_FIND_VERSION)
  set(PACKAGE_VERSION_COMPATIBLE FALSE)
else()
  set(PACKAGE_VERSION_COMPATIBLE TRUE)
  if(PACKAGE_VERSION VERSION_EQUAL PACKAGE_FIND_VERSION)
    set(PACKAGE_VERSION_EXACT TRUE)
  endif()
endif()
"@
Set-Content -Path (Join-Path $cmakeDir "Eigen3ConfigVersion.cmake") -Value $version -Encoding UTF8

Write-Host "Wrote Eigen3Config.cmake -> $cmakeDir" -ForegroundColor Green
Write-Host "find_package(Eigen3) will now succeed for downstream ament plugin builds." -ForegroundColor Green
